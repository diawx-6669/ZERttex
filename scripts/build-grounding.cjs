#!/usr/bin/env node
// Builds worker/src/grounding.json: the ONLY facts the AI is allowed to use.
// Everything comes from src/data with its honesty label. Run after editing
// tours, facts or policies:  npm run grounding
const fs = require('fs');
const path = require('path');
const esbuild = require('esbuild');

const ROOT = path.resolve(__dirname, '..');
const out = esbuild.buildSync({
  stdin: {
    contents: `export { tours } from './src/data/tours'; export { caseFacts, evidence, methodNote } from './src/data/facts'; export { ui } from './src/data/i18n';`,
    resolveDir: ROOT,
    loader: 'ts',
  },
  bundle: true,
  format: 'cjs',
  platform: 'node',
  write: false,
  logLevel: 'silent',
});
const mod = { exports: {} };
new Function('module', 'exports', 'require', out.outputFiles[0].text)(mod, mod.exports, require);
const { tours, caseFacts, evidence, methodNote, ui } = mod.exports;

const en = (l) => l.en;
const zh = (l) => l.zh;
const both = (l) => ({ en: l.en, zh: l.zh });
const items = (arr) => arr.map((x) => ({ ...both(x.label), ...(x.priceKzt ? { priceKzt: x.priceKzt } : {}) }));

const grounding = {
  _about: 'Generated by scripts/build-grounding.cjs from src/data. Do not edit by hand.',
  labels: ['Case fact', 'Verified source', 'Proposal', 'Demo data', 'Needs confirmation'],
  company: {
    label: 'Case fact',
    facts: caseFacts.filter((f) => !/budget/i.test(f.label)).map((f) => `${f.label}: ${f.value}`),
  },
  tours: {
    label: 'Demo data',
    note: 'Tour details and prices are demo data for the prototype. Items under notYetConfirmed are NOT included until the company confirms them in writing.',
    list: tours.map((t) => ({
      id: t.id,
      route: `/tour/${t.id}`,
      name: both(t.name),
      days: t.days,
      startCity: t.hub,
      demoPriceKztPerPerson: t.priceKzt,
      region: both(t.region),
      difficulty: both(t.difficulty),
      bestFor: t.bestFor,
      highlights: t.highlights.map(both),
      included: items(t.inclusions.included),
      optionalExtra: items(t.inclusions.optional),
      notIncluded: items(t.inclusions.notIncluded),
      notYetConfirmed: items(t.inclusions.unconfirmed),
      dayByDay: t.itinerary.map((d) => ({ title: both(d.title), items: d.items.map(en) })),
      packing: t.packing.map(en),
    })),
  },
  market: {
    label: 'Verified source',
    facts: evidence.map((e) => ({ figure: e.figure, en: en(e.text), zh: zh(e.text), source: e.source, date: e.date })),
    methodNote: both(methodNote),
  },
  policies: {
    label: 'Proposal',
    note: 'Team proposals for the real service. Not yet in force.',
    booking: 'Booking in 3 steps: trip, lead traveler, payment. Booking date at least 7 days ahead. 1-12 travelers.',
    payment: 'International cards (Visa, Mastercard etc.) through a payment provider\'s hosted checkout; the company never sees card numbers. Alipay and WeChat Pay are planned after provider approval. Prices are in KZT; USD/CNY amounts are indicative only. The prototype is in TEST MODE: no money moves.',
    refund: [ui.trust.refundSub, ui.trust.refund14, ui.trust.refund4, ui.trust.refund0, ui.trust.refundWeather].map(both),
    trust: 'Before paying, a traveler can watch a guide intro video and request a 5-minute video call with the guide.',
    familySharing: 'Optional family updates share trip status (not live GPS), off by default, stop after the trip.',
    referral: 'Postcard with a referral link; a first-booking discount for the friend is a proposal.',
  },
  needsConfirmation: {
    label: 'Needs confirmation',
    items: [
      'Company registration, tour operator licence and insurance documents: to be provided by the company.',
      'Emergency number 112 in Kazakhstan: listed in the app, official source still to be confirmed.',
      'Park and site entrance fees, exact guesthouse names, Kaindy 4x4 transfer, Chinese-speaking guide on a given date.',
      'Live availability of seats on any date: not available to the assistant; a manager confirms.',
    ],
  },
  routes: ['/tours', '/tour/charyn', '/tour/kolsai', '/tour/turkestan', '/tour/burabay', '/book', '/plan', '/trust', '/trip', '/postcard', 'handoff'],
};

const file = path.join(ROOT, 'worker/src/grounding.json');
fs.writeFileSync(file, JSON.stringify(grounding, null, 1) + '\n');
console.log('written', path.relative(ROOT, file), `(${(fs.statSync(file).size / 1024).toFixed(1)} KB)`);
